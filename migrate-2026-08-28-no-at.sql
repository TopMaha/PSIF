ALTER TABLE psif ADD COLUMN no_at TEXT DEFAULT '';

-- ---- เติมย้อนหลังเท่าที่มีหลักฐานจริง ----
--  ตอนกด "เริ่มดำเนินการ" (ลงเลข + เปลี่ยนสถานะ) ระบบเขียนแจ้งเตือน "🚀 ... เริ่มดำเนินการแล้ว"
--  ให้ผู้รายงานเสมอ — created_at ของแจ้งเตือนใบแรกจึงคือเวลาที่เลขถูกลงจริง
--  เรื่องที่ไม่มีร่องรอยนี้ (ข้อมูลนำเข้าจาก Excel เก่า / Safety บันทึกเลขเฉย ๆ / ผู้รายงานลงเลขเอง)
--  ปล่อยว่างไว้ — รายงานจะแสดง "—" ไม่เดาวันที่ให้ผิด
UPDATE psif
   SET no_at = (SELECT MIN(n.created_at) FROM notifications n
                 WHERE n.psif_id = psif.id AND n.message LIKE '🚀%')
 WHERE COALESCE(no_at,'') = ''
   AND COALESCE(no,'')   <> ''
   AND EXISTS (SELECT 1 FROM notifications n
                WHERE n.psif_id = psif.id AND n.message LIKE '🚀%');
